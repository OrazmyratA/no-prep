// Splits the side-by-side translation sources (src/app/core/language-translations*.ts, every
// language next to each other per key) into one module per language for production builds:
//   src/app/core/i18n/<lang>.ts                      key → text for that language
//   src/app/core/language-dictionary.generated.ts    replaces language-dictionary.ts (angular.json)
// English is bundled; every other language becomes a lazy chunk loaded when it is chosen. Both
// outputs are generated (gitignored) — edit the language-translations*.ts sources as before.
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const core = path.join(__dirname, '..', 'src', 'app', 'core');
const outDir = path.join(core, 'i18n');
const loaderFile = path.join(core, 'language-dictionary.generated.ts');
const HEADER = '// Generated by scripts/split-translations.js from src/app/core/language-translations*.ts. Do not edit.\n';

const typesSource = fs.readFileSync(path.join(core, 'language-types.ts'), 'utf8');
const languages = [...typesSource.match(/SUPPORTED_LANGUAGES = \[([^\]]+)\]/)[1].matchAll(/'(\w+)'/g)].map(m => m[1]);

// Bundle the TypeScript sources into one CommonJS module and evaluate it here.
const bundled = esbuild.buildSync({
  stdin: {
    contents: "export { TRANSLATIONS } from './language-translations'; export { textsFor } from './language-dictionary';",
    resolveDir: core,
    loader: 'ts'
  },
  bundle: true,
  format: 'cjs',
  platform: 'node',
  write: false,
  logLevel: 'error'
});
const mod = { exports: {} };
new Function('module', 'exports', bundled.outputFiles[0].text)(mod, mod.exports);
const { TRANSLATIONS, textsFor } = mod.exports;

const noEnglish = Object.keys(TRANSLATIONS).filter(key => !TRANSLATIONS[key].en);
if (noEnglish.length) console.warn(`[split-translations] keys without English: ${noEnglish.join(', ')}`);

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
let total = 0;
for (const lang of languages) {
  const json = JSON.stringify(textsFor(TRANSLATIONS, lang));
  total += json.length;
  // A JSON string parses much faster than the same data written as an object literal.
  fs.writeFileSync(
    path.join(outDir, `${lang}.ts`),
    `${HEADER}const texts: Readonly<Record<string, string>> = JSON.parse(${JSON.stringify(json)});\nexport default texts;\n`
  );
}

const cases = languages
  .filter(lang => lang !== 'en')
  .map(lang => `    case '${lang}': return import('./i18n/${lang}').then(m => m.default);`)
  .join('\n');
fs.writeFileSync(loaderFile, `${HEADER}// Production replacement for language-dictionary.ts (angular.json fileReplacements).
import type { SupportedLanguage } from './language-types';
import ENGLISH from './i18n/en';

export type LanguageTexts = Readonly<Record<string, string>>;

export const ENGLISH_TEXTS: LanguageTexts = ENGLISH;

export function loadLanguageTexts(lang: SupportedLanguage): Promise<LanguageTexts> {
  switch (lang) {
${cases}
    default: return Promise.resolve(ENGLISH);
  }
}
`);

console.log(`[split-translations] ${Object.keys(TRANSLATIONS).length} keys × ${languages.length} languages -> src/app/core/i18n (${Math.round(total / 1024)} KB)`);
